package io.github.vesas.jdbcprof.capture;

import java.sql.Array;
import java.sql.Blob;
import java.sql.CallableStatement;
import java.sql.Clob;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.NClob;
import java.sql.PreparedStatement;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.SQLXML;
import java.sql.Savepoint;
import java.sql.Statement;
import java.sql.Struct;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

/**
 * Wraps a real {@link Connection} so that the statements it produces
 * — and the transaction events it signals — are captured (spec §5.1).
 *
 * <p>Only the methods named in spec §5.1 are intercepted
 * ({@code prepareStatement}, {@code createStatement}, {@code commit},
 * {@code rollback}, {@code close}). Every other method is straight
 * delegation to the underlying connection.
 *
 * <p>{@code prepareStatement} pre-interns the SQL template at prepare
 * time so the per-execution hot path has only an int id to carry.
 */
final class CapturingConnection implements Connection {

    private static final byte PREPARE = (byte) EventType.PREPARE.ordinal();
    private static final byte COMMIT = (byte) EventType.COMMIT.ordinal();
    private static final byte ROLLBACK = (byte) EventType.ROLLBACK.ordinal();
    private static final byte CLOSE = (byte) EventType.CLOSE.ordinal();

    private final Connection delegate;
    private final CaptureContext ctx;

    CapturingConnection(Connection delegate, CaptureContext ctx) {
        this.delegate = delegate;
        this.ctx = ctx;
    }

    private int internPrepared(String sql) {
        // PreparedStatement SQL is already template-shaped (spec §5.5).
        return ctx.sqlIntern().intern(sql);
    }

    private PreparedStatement wrap(PreparedStatement real, int sqlId,
                                   long startNanos, long durationNanos) {
        ctx.emit(PREPARE, sqlId, startNanos, durationNanos, -1, 0, 0L);
        return new CapturingPreparedStatement(real, ctx, sqlId);
    }

    @Override
    public Statement createStatement() throws SQLException {
        return new CapturingStatement(delegate.createStatement(), ctx);
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
        return new CapturingStatement(
                delegate.createStatement(resultSetType, resultSetConcurrency), ctx);
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency,
                                     int resultSetHoldability) throws SQLException {
        return new CapturingStatement(
                delegate.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability),
                ctx);
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        int id = internPrepared(sql);
        long t0 = System.nanoTime();
        PreparedStatement real = delegate.prepareStatement(sql);
        long t1 = System.nanoTime();
        return wrap(real, id, t0, t1 - t0);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        int id = internPrepared(sql);
        long t0 = System.nanoTime();
        PreparedStatement real = delegate.prepareStatement(sql, autoGeneratedKeys);
        long t1 = System.nanoTime();
        return wrap(real, id, t0, t1 - t0);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
        int id = internPrepared(sql);
        long t0 = System.nanoTime();
        PreparedStatement real = delegate.prepareStatement(sql, columnIndexes);
        long t1 = System.nanoTime();
        return wrap(real, id, t0, t1 - t0);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
        int id = internPrepared(sql);
        long t0 = System.nanoTime();
        PreparedStatement real = delegate.prepareStatement(sql, columnNames);
        long t1 = System.nanoTime();
        return wrap(real, id, t0, t1 - t0);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType,
                                              int resultSetConcurrency) throws SQLException {
        int id = internPrepared(sql);
        long t0 = System.nanoTime();
        PreparedStatement real = delegate.prepareStatement(sql, resultSetType, resultSetConcurrency);
        long t1 = System.nanoTime();
        return wrap(real, id, t0, t1 - t0);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType,
                                              int resultSetConcurrency,
                                              int resultSetHoldability) throws SQLException {
        int id = internPrepared(sql);
        long t0 = System.nanoTime();
        PreparedStatement real = delegate.prepareStatement(sql, resultSetType,
                resultSetConcurrency, resultSetHoldability);
        long t1 = System.nanoTime();
        return wrap(real, id, t0, t1 - t0);
    }

    @Override
    public CallableStatement prepareCall(String sql) throws SQLException {
        return delegate.prepareCall(sql);
    }

    @Override
    public CallableStatement prepareCall(String sql, int resultSetType,
                                         int resultSetConcurrency) throws SQLException {
        return delegate.prepareCall(sql, resultSetType, resultSetConcurrency);
    }

    @Override
    public CallableStatement prepareCall(String sql, int resultSetType,
                                         int resultSetConcurrency,
                                         int resultSetHoldability) throws SQLException {
        return delegate.prepareCall(sql, resultSetType,
                resultSetConcurrency, resultSetHoldability);
    }

    @Override
    public void commit() throws SQLException {
        long t0 = System.nanoTime();
        delegate.commit();
        long t1 = System.nanoTime();
        ctx.emit(COMMIT, -1, t0, t1 - t0, -1, 0, 0L);
    }

    @Override
    public void rollback() throws SQLException {
        long t0 = System.nanoTime();
        delegate.rollback();
        long t1 = System.nanoTime();
        ctx.emit(ROLLBACK, -1, t0, t1 - t0, -1, 0, 0L);
    }

    @Override
    public void rollback(Savepoint savepoint) throws SQLException {
        long t0 = System.nanoTime();
        delegate.rollback(savepoint);
        long t1 = System.nanoTime();
        ctx.emit(ROLLBACK, -1, t0, t1 - t0, -1, 0, 0L);
    }

    @Override
    public void close() throws SQLException {
        long t0 = System.nanoTime();
        delegate.close();
        long t1 = System.nanoTime();
        ctx.emit(CLOSE, -1, t0, t1 - t0, -1, 0, 0L);
    }

    // --- everything below is straight delegation ---

    @Override public String nativeSQL(String sql) throws SQLException { return delegate.nativeSQL(sql); }
    @Override public void setAutoCommit(boolean autoCommit) throws SQLException { delegate.setAutoCommit(autoCommit); }
    @Override public boolean getAutoCommit() throws SQLException { return delegate.getAutoCommit(); }
    @Override public boolean isClosed() throws SQLException { return delegate.isClosed(); }
    @Override public DatabaseMetaData getMetaData() throws SQLException { return delegate.getMetaData(); }
    @Override public void setReadOnly(boolean readOnly) throws SQLException { delegate.setReadOnly(readOnly); }
    @Override public boolean isReadOnly() throws SQLException { return delegate.isReadOnly(); }
    @Override public void setCatalog(String catalog) throws SQLException { delegate.setCatalog(catalog); }
    @Override public String getCatalog() throws SQLException { return delegate.getCatalog(); }
    @Override public void setTransactionIsolation(int level) throws SQLException { delegate.setTransactionIsolation(level); }
    @Override public int getTransactionIsolation() throws SQLException { return delegate.getTransactionIsolation(); }
    @Override public SQLWarning getWarnings() throws SQLException { return delegate.getWarnings(); }
    @Override public void clearWarnings() throws SQLException { delegate.clearWarnings(); }
    @Override public Map<String, Class<?>> getTypeMap() throws SQLException { return delegate.getTypeMap(); }
    @Override public void setTypeMap(Map<String, Class<?>> map) throws SQLException { delegate.setTypeMap(map); }
    @Override public void setHoldability(int holdability) throws SQLException { delegate.setHoldability(holdability); }
    @Override public int getHoldability() throws SQLException { return delegate.getHoldability(); }
    @Override public Savepoint setSavepoint() throws SQLException { return delegate.setSavepoint(); }
    @Override public Savepoint setSavepoint(String name) throws SQLException { return delegate.setSavepoint(name); }
    @Override public void releaseSavepoint(Savepoint savepoint) throws SQLException { delegate.releaseSavepoint(savepoint); }
    @Override public Clob createClob() throws SQLException { return delegate.createClob(); }
    @Override public Blob createBlob() throws SQLException { return delegate.createBlob(); }
    @Override public NClob createNClob() throws SQLException { return delegate.createNClob(); }
    @Override public SQLXML createSQLXML() throws SQLException { return delegate.createSQLXML(); }
    @Override public boolean isValid(int timeout) throws SQLException { return delegate.isValid(timeout); }
    @Override public void setClientInfo(String name, String value) throws SQLClientInfoException { delegate.setClientInfo(name, value); }
    @Override public void setClientInfo(Properties properties) throws SQLClientInfoException { delegate.setClientInfo(properties); }
    @Override public String getClientInfo(String name) throws SQLException { return delegate.getClientInfo(name); }
    @Override public Properties getClientInfo() throws SQLException { return delegate.getClientInfo(); }
    @Override public Array createArrayOf(String typeName, Object[] elements) throws SQLException { return delegate.createArrayOf(typeName, elements); }
    @Override public Struct createStruct(String typeName, Object[] attributes) throws SQLException { return delegate.createStruct(typeName, attributes); }
    @Override public void setSchema(String schema) throws SQLException { delegate.setSchema(schema); }
    @Override public String getSchema() throws SQLException { return delegate.getSchema(); }
    @Override public void abort(Executor executor) throws SQLException { delegate.abort(executor); }
    @Override public void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException { delegate.setNetworkTimeout(executor, milliseconds); }
    @Override public int getNetworkTimeout() throws SQLException { return delegate.getNetworkTimeout(); }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        return delegate.unwrap(iface);
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) throws SQLException {
        return iface.isInstance(this) || delegate.isWrapperFor(iface);
    }
}
